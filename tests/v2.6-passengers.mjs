import assert from 'node:assert/strict';
import { createCity } from '../src/city.js';
import { createNetwork, routeLine } from '../src/network.js';
import { createState } from '../src/state.js';
import { createPassenger, PASSENGER_STATES, passengerStats, resetPassengerIds } from '../src/passengers.js';
import { createLine, finishLine } from '../src/engine.js';

resetPassengerIds();
const city = createCity('V26-PASSENGERS');
const state = createState(city);
state.network = createNetwork(city);
const log = () => {};
const a = city.stops[0].id, b = city.stops[1].id, c = city.stops[2].id;
createLine(state);
state.pendingStops = [a,b,c];
assert.equal(finishLine(state, log, routeLine), true);
const p = createPassenger({ originId:a, destinationId:c, createdAt:state.time });
p.itinerary = [{lineId:state.lines[0].id, from:a, to:c}];
state.passengers.push(p);
assert.equal(p.state, PASSENGER_STATES.WAITING);
p.state = PASSENGER_STATES.BOARDING;
p.vehicleId = state.vehicles[0].id;
p.state = PASSENGER_STATES.ON_VEHICLE;
assert.equal(passengerStats(state).ON_VEHICLE, 1);
p.legIndex = 0;
p.state = PASSENGER_STATES.ARRIVED;
p.vehicleId = null;
assert.equal(passengerStats(state).ARRIVED, 1);
const impossible = createPassenger({originId:a,destinationId:c});
impossible.state = PASSENGER_STATES.ABANDONED;
state.passengers.push(impossible);
assert.equal(passengerStats(state).ABANDONED, 1);
console.log(JSON.stringify({ok:true, states:passengerStats(state)}));
